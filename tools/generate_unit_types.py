def class_name(unit_type: UnitTypeId) -> str:
    """The class name of a type: `SIEGE_TANK_SIEGED` is `SiegeTankSieged`."""
    return "".join(part.capitalize() for part in unit_type.name.split("_"))


def roles(unit_type: UnitTypeId, row: UnitTypeData, counted_as: frozenset[UnitTypeId]) -> list[str]:
    """The groups of what `unit_type`, whose row is `row` and which the tables count as each of `counted_as`, is
    for."""
    curated = (
        ("Worker", WORKERS),
        ("Townhall", TOWNHALLS),
        ("CollapsibleTower", COLLAPSIBLE_TOWERS),
        ("CollapsibleTowerDebris", COLLAPSIBLE_TOWER_DEBRIS),
        ("Critter", CRITTERS),
        ("AnyChangeling", CHANGELINGS),
        ("AnyCreepTumor", CREEP_TUMORS),
        ("AnyLocust", LOCUSTS),
        ("Cocoon", COCOON_PRODUCTS.keys()),
        *GAS_BUILDINGS_ON_EITHER_GEYSER.items(),
        *TWO_FORMS.items(),
    )
    found = [role for role, members in curated if unit_type in members]
    if unit_type in TOWNHALLS and row.race in RACE_TOWNHALLS:
        found.append(RACE_TOWNHALLS[row.race])
    if row.has_minerals:
        found.append("AnyMineralField")
    if row.has_vespene:
        found.append("GasBuilding" if row.race in RACES else "AnyVespeneGeyser")
    found += [group for group, plain in COUNTED_AS.items() if unit_type is plain or plain in counted_as]
    found += [group for group, prefix in MAP_OBJECTS.items() if unit_type.name.startswith(prefix)]
    return found + [HOLDING_GROUPS[role] for role in found if role in HOLDING_GROUPS]


def producer_groups(tables: GameData) -> dict[UnitTypeId, list[str]]:
    """The groups of `PRODUCED_BY` each unit type is in: those of the structures the tables say make it, a structure's
    own add-ons and lifted form left out, or make another of its forms, as a factory does a siege tank sieged."""
    groups: dict[UnitTypeId, list[str]] = {}
    for group, producer in PRODUCED_BY.items():
        made = {
            unit_type
            for unit_type, row in tables.units.items()
            if producer in row.producers and Attribute.STRUCTURE not in row.attributes
        }
        made |= {form for forms in TWO_FORMS.values() if forms & made for form in forms}
        for unit_type in made:
            groups.setdefault(unit_type, []).append(group)
    return groups


def table_groups(row: UnitTypeData) -> tuple[str, ...]:
    """The race and structure groups the tables put the type of `row` in, the narrowest: `TerranStructure`, or
    `Structure` for a structure of no race; `NonStructure` and `Terran`, or `NonStructure` alone for a type of no race
    that is no structure. `NonStructure` comes first, as it does in a group's sorted bases, so that every class names
    the two in one order."""
    race = RACES.get(row.race)
    if Attribute.STRUCTURE in row.attributes:
        return (f"{race}Structure",) if race else ("Structure",)
    return ("NonStructure", race) if race else ("NonStructure",)


def ancestors(group: str, bases: dict[str, tuple[str, ...]]) -> set[str]:
    """Every group `group` is in, by the bases of each group in `bases`."""
    return set().union(*({base} | ancestors(base, bases) for base in bases.get(group, ())))


def narrowest(groups: list[str], bases: dict[str, tuple[str, ...]]) -> tuple[str, ...]:
    """`groups` in order, each once, less each one another of them is in."""
    inner = set().union(*(ancestors(group, bases) for group in groups))
    return tuple(dict.fromkeys(group for group in groups if group not in inner))


def render(answer: sc2api_pb2.ResponseData) -> str:
    """The module source for the types in the game's tables, `answer`."""
    tables = GameData(answer)
    counted_as = tech_aliases(answer)
    groups_of = {unit_type: table_groups(tables.units[unit_type]) for unit_type in UnitTypeId}
    produced = producer_groups(tables)
    found = {
        unit_type: roles(unit_type, tables.units[unit_type], counted_as.get(unit_type, frozenset()))
        + produced.get(unit_type, [])
        for unit_type in UnitTypeId
    }
    bases: dict[str, tuple[str, ...]] = {
        "Structure": ("AnyType",),
        "NonStructure": ("AnyType",),
        **{name: ("AnyType",) for name in RACES.values()},
        **{f"{name}Structure": (name, "Structure") for name in RACES.values()},
    }
    docstrings = {
        "Structure": "A type the game's tables give the structure attribute.",
        "NonStructure": "A type the game's tables do not give the structure attribute.",
        **{name: f"A {name} type." for name in RACES.values()},
        **{f"{name}Structure": f"A {name} structure." for name in RACES.values()},
        **ROLES,
    }
    members = {role: {unit_type for unit_type in UnitTypeId if role in found[unit_type]} for role in ROLES}
    for role in ROLES:
        holding = [other for other in ROLES if other != role and members[role] <= members[other]]
        for other in holding:
            if members[other] == members[role]:
                raise ValueError(f"{role} and {other} hold the same types")
        # The race and structure groups every type of the role is in.
        shared = set.intersection(
            *(
                set(groups_of[unit_type]).union(*(ancestors(group, bases) for group in groups_of[unit_type]))
                for unit_type in members[role]
            )
        )
        bases[role] = narrowest([*holding, *sorted(shared)], bases)
    blocks = [HEADER]
    for name, docstring in docstrings.items():
        equivalence_declaration = "\n        types_are_equivalent = True\n" if name in TWO_FORMS else ""
        blocks.append(
            f'    class {name}({", ".join(bases[name])}):\n        """{docstring}"""\n{equivalence_declaration}'
        )
    names = set(docstrings)
    for unit_type in sorted(UnitTypeId, key=class_name):
        name = class_name(unit_type)
        if name in names:
            raise ValueError(f"{unit_type!r} would be named {name}, which is already taken")
        names.add(name)
        # A base named before a subclass of it has no consistent method resolution order.
        type_bases = ", ".join(narrowest([*groups_of[unit_type], *found[unit_type]], bases))
        blocks.append(f"    class {name}({type_bases}):\n        id = UnitTypeId.{unit_type.name}\n")
    blocks.append(equivalent_types_source())
    return "\n".join(blocks)


def equivalent_types_source() -> str:
    """The source of `EQUIVALENT_UNIT_TYPES`, from the groups whose types are equivalent, which are those of
    `TWO_FORMS`, each type in one of them at most."""
    seen: set[UnitTypeId] = set()
    for group, types in TWO_FORMS.items():
        if shared := seen & types:
            raise ValueError(f"{group} holds {sorted(shared)}, which another group of two forms holds")
        seen |= types
    return '''
EQUIVALENT_UNIT_TYPES: Final[Mapping[UnitTypeId, type[UnitType.AnyType]]] = MappingProxyType(
    {
        cls.id: next((group for group in cls.__mro__[1:-1] if group.types_are_equivalent), cls)
        for cls in vars(UnitType).values()
        if isinstance(cls, type) and "id" in vars(cls)
    }
)
"""Each type's `UnitTypeData.equivalent_types`: the group it is in whose types are equivalent, or else its own class."""
'''


def corpus_answer() -> sc2api_pb2.ResponseData:
    """The tables of the first corpus game, as the game answered them."""
    recording = Recording(sorted(CORPUS.glob("*.sc2rec"))[0])
    return next(exchange.response.data for exchange in recording if exchange.response.HasField("data"))


def tech_aliases(answer: sc2api_pb2.ResponseData) -> dict[UnitTypeId, frozenset[UnitTypeId]]:
    """The types the game's tables, `answer`, count each type as, their `tech_alias`, where both are curated: a command
    center, for an orbital command. A type they count as nothing else is left out."""
    return {
        unit_type: aliases
        for row in answer.units
        if (unit_type := UnitTypeId.get(row.unit_id)) is not None
        and (aliases := frozenset(filter(None, map(UnitTypeId.get, row.tech_alias))))
    }


