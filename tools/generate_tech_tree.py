def read(findings: Mapping[str, object], upgrade_findings: Mapping[str, object]) -> TechTree:
    """The tech tree for what the curated ids name, from `findings` and `upgrade_findings` as the sweeps write them.

    A unit type offered a creation ability that turned it into something else is taken as not offered it: once Burrow
    is researched, a zergling is offered every zerg unit's burrow, and burrows as a zergling whichever it is ordered.

    Raises `ValueError` where a requirement is something no curated id names; where a required add-on was not seen to
    count only on the unit's own structure; where a unit type is offered an ability whose requirements were never read,
    which would otherwise read as needing nothing; where the sweep did not see an ability in
    `gamedata/_techtree/_overrides.py` make its unit type; where that file lists more than one ability for a type the
    table names no working ability for; or where two abilities research one upgrade. Also raises for whatever
    `read_upgrades` raises for, and where the two sweeps played different builds.
    """
    if findings["base_build"] != upgrade_findings["base_build"]:
        raise ValueError(
            f"the tech tree was swept on build {findings['base_build']} and the upgrades on "
            f"{upgrade_findings['base_build']}"
        )
    found = read_upgrades(upgrade_findings)
    trials = _trials(findings)
    made = {(int(ability), product) for _, ability, product, result in trials if result in ("morph", "build")}
    if unconfirmed := sorted(
        f"{u.name} by {a.name}" for a, u in UNNAMED_CREATION_ABILITIES.items() if (int(a), u) not in made
    ):
        raise ValueError(f"the sweep did not see these make their unit type: {', '.join(unconfirmed)}")

    # Read by the game's own ids, which tell apart what a type is offered of an action several types perform: a
    # zergling offered a roach's burrow burrows as a zergling.
    turned = {(performer, ability) for performer, ability, _, result in trials if result == "other"}
    offered: dict[UnitTypeId, set[RawAbilityId]] = {}
    for type_name, ability_names in _mapping(findings["offered"]).items():
        if (unit_type := _unit_type(type_name)) is not None:
            abilities = filter(None, map(_game_ability, _strings(ability_names)))
            offered[unit_type] = {
                ability for ability in abilities if _fold(ability) and (unit_type, ability) not in turned
            }

    needs: dict[tuple[UnitTypeId, RawAbilityId], TechRequirements] = {}
    for record in _records(findings["requirements"]):
        performer, ability = _unit_type(str(record["performer"])), _game_ability(str(record["ability"]))
        if performer is None or ability is None or ability not in offered.get(performer, ()):
            continue
        structures = frozenset(_required(_unit_type, record["structures"]))
        if any(_is_add_on(structure) for structure in structures) and not record["attached"]:
            raise ValueError(f"{performer.name} is offered {ability.name} with another structure's add-on")
        needs[performer, ability] = TechRequirements(structures, frozenset(_required(_upgrade, record["upgrades"])))
    pairs = [(unit, ability) for unit, abilities in offered.items() for ability in abilities]
    if unread := sorted(f"{unit.name} {ability.name}" for unit, ability in pairs if (unit, ability) not in needs):
        raise ValueError(f"what these need was never read: {', '.join(unread)}")

    game_creation_abilities = _creation_abilities(findings)
    ability_requirements = {
        unit: MappingProxyType(_folded_needs(unit, abilities, needs)) for unit, abilities in offered.items()
    }
    creation_abilities = {unit: _folded(ability) for unit, ability in game_creation_abilities.items()}
    ability_products = {
        ability: MappingProxyType(products_by_maker)
        for ability, products_by_maker in _products(game_creation_abilities, offered, findings).items()
    }
    # A pylon stands in its own field and needs no power, though the sweep once recorded one read as powered.
    power_consumers = frozenset(filter(None, map(_unit_type, _strings(findings["powered"])))) - {UnitTypeId.PYLON}
    unit_type_requirements, upgrade_requirements = _requirements_by_product(
        ability_requirements, ability_products, creation_abilities
    )
    research_abilities = _research_abilities(ability_products)
    return TechTree(
        base_build=int(str(findings["base_build"])),
        unit_types=TechTreeUnitTypes(
            ability_requirements=MappingProxyType(ability_requirements),
            creation_abilities=MappingProxyType(creation_abilities),
            producers=MappingProxyType(_producers_by_unit_type(ability_products, creation_abilities)),
            creation_requirements=MappingProxyType(unit_type_requirements),
            morph_sources=MappingProxyType(_morph_sources(trials, creation_abilities)),
            power_consumers=power_consumers,
            upgrades=MappingProxyType(
                {unit_type: MappingProxyType(upgrades) for unit_type, upgrades in found.unit_types.items()}
            ),
        ),
        abilities=TechTreeAbilities(
            performers=MappingProxyType(_performers_by_ability(ability_requirements)),
            products=MappingProxyType(ability_products),
            cancels=MappingProxyType(_cancels(findings)),
        ),
        upgrades=TechTreeUpgrades(
            research_abilities=MappingProxyType(research_abilities),
            researchers=MappingProxyType(_researchers(research_abilities, ability_products)),
            requirements=MappingProxyType(upgrade_requirements),
            types=MappingProxyType(found.types),
            levels=MappingProxyType(found.levels),
        ),
    )


def _folded_needs(
    unit_type: UnitTypeId,
    abilities: Iterable[RawAbilityId],
    needs: Mapping[tuple[UnitTypeId, RawAbilityId], TechRequirements],
) -> dict[AbilityId, TechRequirements]:
    """What `unit_type` needs for each ability it is offered, by the curated id. Raises `ValueError` where two of the
    game's ids one curated id stands for need different things, which one id could not say."""
    folded: dict[AbilityId, TechRequirements] = {}
    for ability in sorted(abilities, key=int):
        curated = _folded(ability)
        if folded.setdefault(curated, needs[unit_type, ability]) != needs[unit_type, ability]:
            raise ValueError(f"{unit_type.name} needs different things for the ids {curated.name} stands for")
    return folded


@dataclass(frozen=True, slots=True)
class Upgrades:
    """What the upgrade sweep's findings say about what the curated ids name."""

    unit_types: dict[UnitTypeId, dict[UpgradeId, UnitTypeUpgrade]]
    """Every upgrade that affects each unit type, and what it adds to the type's row."""
    types: dict[UpgradeId, UpgradeType]
    """The kind each upgrade is: the upgrade level a unit reports it adds to."""
    levels: dict[UpgradeId, int]
    """Which level of its line each leveled upgrade is."""


def read_upgrades(upgrade_findings: Mapping[str, object]) -> Upgrades:
    """What each upgrade adds to each curated unit type, and which reported upgrade level it raises.

    An upgrade affects a unit type where it changes the type's row or raises a level units of the type report, as the
    void ray's attack upgrades do though it has no weapon in the rows. An upgrade that raises a level on any unit is
    taken to raise it for every type whose row it changes, since a type the sweep put up none of reports nothing. A
    level is the number the curated name ends in; an upgrade that raises a report but has no number, such as Chitinous
    Plating, is no level.

    Raises `ValueError` where the sweep found something the changes do not account for; where one research finished
    more than one upgrade; where a change is to a weapon's attacks or cooldown, which the tables cannot hold; where an
    upgrade no curated id names affects a curated unit type; where one upgrade raises more than one kind of report; or
    where the levels of one kind affecting a type are not 1 onwards or add different amounts.
    """
    if unexplained := _strings(upgrade_findings["unexplained"]):
        raise ValueError(f"the changes do not account for: {'; '.join(unexplained)}")
    unit_types: defaultdict[UnitTypeId, dict[UpgradeId, UnitTypeUpgrade]] = defaultdict(dict)
    kinds: dict[UpgradeId, UpgradeType] = {}
    for record in _records(upgrade_findings["research"]):
        names = _strings(record["upgrades"])
        changes = _mapping(record["changes"])
        raised = {UpgradeType[kind.upper()]: _strings(types) for kind, types in _mapping(record["levels"]).items()}
        raised = {kind: types for kind, types in raised.items() if types}
        if len(names) != 1:
            if changes or raised:
                raise ValueError(f"one research finished {', '.join(names)}, which cannot be told apart")
            continue
        affected = {name for name in changes if _unit_type(name)} | {
            name for types in raised.values() for name in types if _unit_type(name)
        }
        if (upgrade := _upgrade(names[0])) is None:
            if affected:
                raise ValueError(f"{names[0]} affects {', '.join(sorted(affected))}, and no curated id names it")
            continue
        if len(raised) > 1:
            raise ValueError(
                f"{names[0]} raises the {' and '.join(sorted(k.name for k in raised))} levels units report"
            )
        if raised:
            kinds[upgrade] = next(iter(raised))
        for type_name in affected:
            change = _mapping(changes.get(type_name, {}))
            unit_types[_required_unit_type(type_name)][upgrade] = _unit_type_upgrade(names[0], type_name, change)
    levels = {upgrade: level for upgrade in kinds if (level := _level(upgrade))}
    for unit_type, upgrades in unit_types.items():
        for kind in UpgradeType:
            leveled = sorted((levels[u], u) for u in upgrades if kinds.get(u) is kind and u in levels)
            if [level for level, _ in leveled] != list(range(1, len(leveled) + 1)):
                raise ValueError(f"the {kind.name} levels affecting {unit_type.name} are not 1 onwards")
            if any(upgrades[u] != upgrades[leveled[0][1]] for _, u in leveled):
                raise ValueError(f"the {kind.name} levels of {unit_type.name} add different amounts")
    return Upgrades(dict(unit_types), kinds, levels)


def _level(upgrade: UpgradeId) -> int:
    """The number `upgrade`'s curated name ends in, or 0."""
    last = upgrade.name.rsplit("_", 1)[-1]
    return int(last) if last.isdigit() else 0


def _required_unit_type(name: str) -> UnitTypeId:
    if (unit_type := _unit_type(name)) is None:
        raise ValueError(f"{name} is no curated unit type")
    return unit_type


def uncurated_upgraded(upgrade_findings: Mapping[str, object]) -> frozenset[str]:
    """The unit types upgrades change that no curated id names, in the raw catalog's spelling."""
    records = _records(upgrade_findings["research"])
    return frozenset(name for record in records for name in _mapping(record["changes"]) if _unit_type(name) is None)


def _unit_type_upgrade(upgrade: str, unit_type: str, change: Mapping[str, object]) -> UnitTypeUpgrade:
    """`change`, as the sweep writes it, in the tables' terms: speed in distance per second at the game's Faster speed
    rather than Normal, as `UnitTypeData.speed` is."""
    weapons: list[WeaponUpgrade] = []
    for weapon in _records(change.get("weapons", [])):
        if "attacks" in weapon or "cooldown" in weapon:
            raise ValueError(f"{upgrade} changes the attacks or cooldown of a weapon of {unit_type}")
        bonuses = _mapping(weapon.get("bonuses", {}))
        weapons.append(
            WeaponUpgrade(
                damage=float(str(weapon.get("damage", 0.0))),
                damage_bonuses=MappingProxyType(
                    {Attribute[name.upper()]: float(str(bonus)) for name, bonus in bonuses.items()}
                ),
                range=float(str(weapon.get("range", 0.0))),
            )
        )
    # Rounded to what the game's 32-bit floats hold; the conversion otherwise adds spurious digits.
    speed = round(float(str(change.get("speed", 0.0))) * FASTER_PER_NORMAL_SPEED, 6)
    return UnitTypeUpgrade(armor=float(str(change.get("armor", 0.0))), speed=speed, weapons=tuple(weapons))


def uncurated(findings: Mapping[str, object]) -> frozenset[str]:
    """What the curated unit types are offered that no curated ability names, in the raw catalog's spelling."""
    offered = _mapping(findings["offered"]).items()
    names = (name for type_name, abilities in offered if _unit_type(type_name) for name in _strings(abilities))
    return frozenset(name for name in names if _ability(name) is None)


def _cancels(findings: Mapping[str, object]) -> dict[AbilityId, AbilityId]:
    """The cancel a structure was offered for each thing it was set making, where the curated ids name both. Raises
    `ValueError` where the game's ids one curated id stands for were offered different cancels."""
    cancels: dict[AbilityId, AbilityId] = {}
    for work_name, cancel_name in _mapping(findings["cancels"]).items():
        work, cancel = _game_ability(work_name), _game_ability(str(cancel_name))
        if work is None or cancel is None or (curated := _fold(work)) is None or (by := _fold(cancel)) is None:
            continue
        if cancels.setdefault(curated, by) is not by:
            raise ValueError(f"the ids {curated.name} stands for are cancelled by different ids")
    return cancels


def _creation_abilities(findings: Mapping[str, object]) -> dict[UnitTypeId, RawAbilityId]:
    """The game's own ability that makes each unit type: the game's table's where that works, else the unnamed creation
    ability, of which there may be only one."""
    named = {
        unit_type: ability
        for type_name, ability_name in _mapping(findings["creation_abilities"]).items()
        if (unit_type := _unit_type(type_name)) and (ability := _game_ability(str(ability_name))) and _fold(ability)
    }
    unnamed: defaultdict[UnitTypeId, set[AbilityId]] = defaultdict(set)
    for ability, unit_type in UNNAMED_CREATION_ABILITIES.items():
        if unit_type not in named:
            unnamed[unit_type].add(ability)
    if ambiguous := sorted(unit_type.name for unit_type, abilities in unnamed.items() if len(abilities) > 1):
        raise ValueError(f"the table names no working ability for these, and more than one is listed: {ambiguous}")
    return named | {unit_type: RawAbilityId(ability) for unit_type, (ability,) in unnamed.items()}


def _products(
    creation: Mapping[UnitTypeId, RawAbilityId],
    offered: Mapping[UnitTypeId, Iterable[RawAbilityId]],
    findings: Mapping[str, object],
) -> dict[AbilityId, dict[UnitTypeId, UnitTypeId | UpgradeId]]:
    """The unit type or upgrade each ability makes, by the unit type that carries it out, including the unnamed creation
    abilities and the research abilities the table misnames.

    Each of the game's ids makes one thing; the curated id several stand for makes what each type's own does. A type
    that shares its ability with the type the table names it for, as a rich refinery shares the plain build with a
    refinery, leaves the table's product in place. An id no type is offered is carried out by the types offered
    another the same curated id stands for and making nothing else by it, as a liberator is offered the siege whose
    reported id the table names, or by the type `SELF_MORPHS` names, as a gateway turns itself into a warp gate; one
    nothing carries out is left out, and `tests/test_tech_tree.py` checks that every unit type and upgrade is still
    made by something. Raises `ValueError` where a type would make two things by one curated id.
    """
    made: dict[RawAbilityId, UnitTypeId | UpgradeId] = {}
    for unit_type, ability in creation.items():
        if UNNAMED_CREATION_ABILITIES.get(_folded(ability)) is not unit_type:
            made.setdefault(ability, unit_type)
    for ability, unit_type in UNNAMED_CREATION_ABILITIES.items():
        made.setdefault(RawAbilityId(ability), unit_type)
    for upgrade_name, ability_name in _mapping(findings["research_abilities"]).items():
        if (upgrade := _upgrade(upgrade_name)) and (ability := _game_ability(str(ability_name))) and _fold(ability):
            made[ability] = upgrade
    for upgrade, ability in MISNAMED_RESEARCH_ABILITIES.items():
        made[RawAbilityId(ability)] = upgrade
    makers: defaultdict[RawAbilityId, set[UnitTypeId]] = defaultdict(set)
    curated_makers: defaultdict[AbilityId, set[UnitTypeId]] = defaultdict(set)
    for unit_type, abilities in offered.items():
        for ability in abilities:
            makers[ability].add(unit_type)
            curated_makers[_folded(ability)].add(unit_type)
    products: defaultdict[AbilityId, dict[UnitTypeId, UnitTypeId | UpgradeId]] = defaultdict(dict)
    # The ids some type is offered first, so that one no type is offered goes to the types left making nothing by the
    # curated id it reads as.
    for ability, product in sorted(made.items(), key=lambda entry: not makers.get(entry[0])):
        curated = _folded(ability)
        self_morph = SELF_MORPHS.get(curated)
        carried_out_by = (
            makers.get(ability)
            or curated_makers.get(curated, set()) - products[curated].keys()
            or ({self_morph} if self_morph is not None else set())
        )
        for maker in carried_out_by:
            if products[curated].setdefault(maker, product) is not product:
                raise ValueError(f"{maker.name} makes two things by {curated.name}")
    return dict(products)


def _performers_by_ability(
    ability_requirements: Mapping[UnitTypeId, Mapping[AbilityId, TechRequirements]],
) -> dict[AbilityId, frozenset[UnitTypeId]]:
    """The unit types offered each ability, inverted from what each type is offered."""
    performers_by_ability: defaultdict[AbilityId, set[UnitTypeId]] = defaultdict(set)
    for unit_type, abilities in ability_requirements.items():
        for ability in abilities:
            performers_by_ability[ability].add(unit_type)
    return {ability: frozenset(unit_types) for ability, unit_types in performers_by_ability.items()}


def _research_abilities(
    ability_products: Mapping[AbilityId, Mapping[UnitTypeId, UnitTypeId | UpgradeId]],
) -> dict[UpgradeId, AbilityId]:
    """The ability that researches each upgrade, inverted from what each ability makes. Raises `ValueError` where two
    abilities research one upgrade."""
    research_abilities: dict[UpgradeId, AbilityId] = {}
    for ability, products_by_maker in ability_products.items():
        for product in products_by_maker.values():
            if isinstance(product, UpgradeId) and research_abilities.setdefault(product, ability) is not ability:
                raise ValueError(f"{product.name} is researched by two abilities")
    return research_abilities


def _researchers(
    research_abilities: Mapping[UpgradeId, AbilityId],
    ability_products: Mapping[AbilityId, Mapping[UnitTypeId, UnitTypeId | UpgradeId]],
) -> dict[UpgradeId, frozenset[UnitTypeId]]:
    """The unit types that research each upgrade: those its research ability researches it for."""
    return {
        upgrade: frozenset(
            researcher for researcher, product in ability_products.get(ability, {}).items() if product is upgrade
        )
        for upgrade, ability in research_abilities.items()
    }


def _requirements_by_product(
    ability_requirements: Mapping[UnitTypeId, Mapping[AbilityId, TechRequirements]],
    ability_products: Mapping[AbilityId, Mapping[UnitTypeId, UnitTypeId | UpgradeId]],
    creation_abilities: Mapping[UnitTypeId, AbilityId],
) -> tuple[dict[UnitTypeId, TechRequirements], dict[UpgradeId, TechRequirements]]:
    """What each unit type and each upgrade needs first: every structure and upgrade each type making it needs for the
    ability it makes it by, together, a warp gate's for its warp-ins with a gateway's for its trains. A type whose
    creation ability names another product takes what that ability's performers need for it, as a rich refinery takes
    a refinery's. One that needs nothing is left out.

    The two are kept apart, as a unit type and an upgrade of one number are equal keys.
    """
    unit_type_needs: defaultdict[UnitTypeId, list[TechRequirements]] = defaultdict(list)
    upgrade_needs: defaultdict[UpgradeId, list[TechRequirements]] = defaultdict(list)
    for performer, needs_by_ability in ability_requirements.items():
        for ability, needs in needs_by_ability.items():
            product = ability_products.get(ability, {}).get(performer)
            if isinstance(product, UpgradeId):
                upgrade_needs[product].append(needs)
            elif product is not None:
                unit_type_needs[product].append(needs)
    for unit_type, ability in creation_abilities.items():
        products_by_maker = ability_products.get(ability, {})
        if products_by_maker and not any(product is unit_type for product in products_by_maker.values()):
            for performer in products_by_maker:
                if (needs := ability_requirements.get(performer, {}).get(ability)) is not None:
                    unit_type_needs[unit_type].append(needs)
    return _all_needed(unit_type_needs), _all_needed(upgrade_needs)


def _all_needed[ProductT](
    needs_by_product: Mapping[ProductT, list[TechRequirements]],
) -> dict[ProductT, TechRequirements]:
    """Every structure and upgrade any of each product's needs names, together, leaving out a product that needs
    nothing."""
    all_needed: dict[ProductT, TechRequirements] = {}
    for product, needs in needs_by_product.items():
        structures = frozenset[UnitTypeId]().union(*(each.structures for each in needs))
        upgrades = frozenset[UpgradeId]().union(*(each.upgrades for each in needs))
        if structures or upgrades:
            all_needed[product] = TechRequirements(structures, upgrades)
    return all_needed


def _producers_by_unit_type(
    ability_products: Mapping[AbilityId, Mapping[UnitTypeId, UnitTypeId | UpgradeId]],
    creation_abilities: Mapping[UnitTypeId, AbilityId],
) -> dict[UnitTypeId, frozenset[UnitTypeId]]:
    """The unit types that make each unit type, inverted from what each ability makes, and for a type whose creation
    ability names another product, the types that carry that ability out. A type nothing makes is left out."""
    producers_by_type: defaultdict[UnitTypeId, set[UnitTypeId]] = defaultdict(set)
    for products_by_maker in ability_products.values():
        for producer, product in products_by_maker.items():
            if isinstance(product, UnitTypeId):
                producers_by_type[product].add(producer)
    for unit_type, ability in creation_abilities.items():
        products_by_maker = ability_products.get(ability, {})
        if products_by_maker and not any(product is unit_type for product in products_by_maker.values()):
            producers_by_type[unit_type].update(products_by_maker)
    return {unit_type: frozenset(type_producers) for unit_type, type_producers in producers_by_type.items()}


def _morph_sources(
    trials: Iterable[Trial], creation_abilities: Mapping[UnitTypeId, AbilityId]
) -> dict[UnitTypeId, UnitTypeId]:
    """The type each unit type is made from, from the trials that used up the unit ordered, and for a type made by an
    ability in `SELF_MORPHS`, which no trial saw, the type that turns itself into it there: a gateway, for a warp gate.

    Where several types can be used up making one, the source is the one the others are themselves made from: an
    overseer is made from an overlord, and from the overlord transport an overlord becomes.
    """
    used_up: defaultdict[UnitTypeId, set[UnitTypeId]] = defaultdict(set)
    for performer, _, product, result in trials:
        if result == "morph":
            used_up[product].add(performer)
    sources: dict[UnitTypeId, UnitTypeId] = {}
    for product, performers in used_up.items():
        roots = [performer for performer in performers if not used_up.get(performer, set()) & performers]
        if len(roots) == 1:
            sources[product] = roots[0]
    for unit_type, creation_ability in creation_abilities.items():
        if (self_morphing_type := SELF_MORPHS.get(creation_ability)) is not None:
            sources.setdefault(unit_type, self_morphing_type)
    return sources


def render(tech_tree: TechTree) -> str:
    """The module source for `tech_tree`."""
    return HEADER.format(base_build=tech_tree.base_build) + f"TECH_TREE: Final = {_literal(tech_tree, 0)}\n"


def output(tech_tree: TechTree) -> Path:
    """The path of the module for `tech_tree`."""
    return TECHTREE / f"_build_{tech_tree.base_build}.py"


def _literal(value: object, indent: int) -> str:
    """`value` as a Python expression starting at column `indent`: one member per line, each bracket beside the
    parenthesis it opens in, and one line per ability entry and per set inside a mapping. `pyproject.toml` keeps the
    module out of ruff's formatter and line length, which would undo both."""
    pad, inner = " " * indent, " " * (indent + 4)
    if isinstance(value, IntEnum | bool | int | float | tuple):
        return _inline(value)
    if isinstance(value, frozenset):
        if not value:
            return "frozenset()"
        members = "".join(f"{inner}{_literal(member, indent + 4)},\n" for member in sorted(value, key=_order))
        return f"frozenset({{\n{members}{pad}}})"
    if isinstance(value, Mapping):
        if not value:
            return "MappingProxyType({})"
        entries = sorted(value.items(), key=lambda entry: _order(entry[0]))
        lines = "".join(f"{inner}{_literal(k, indent + 4)}: {_mapped_literal(v, indent + 4)},\n" for k, v in entries)
        return f"MappingProxyType({{\n{lines}{pad}}})"
    if is_dataclass(value) and not isinstance(value, type):
        if not isinstance(value, _RECORDS_WRITTEN_A_FIELD_PER_LINE):
            return _inline(value)
        lines = "".join(f"{inner}{name}={_literal(member, indent + 4)},\n" for name, member in _given_fields(value))
        return f"{type(value).__name__}(\n{lines}{pad})"
    raise TypeError(f"no literal for {value!r}")


# The tech tree and its parts. Any other dataclass, a requirement or what an upgrade adds, is written on one line.
_RECORDS_WRITTEN_A_FIELD_PER_LINE = (TechTree, TechTreeUnitTypes, TechTreeAbilities, TechTreeUpgrades)


def _mapped_literal(value: object, indent: int) -> str:
    """`value`, an entry's value in a mapping, as `_literal` writes it, but on one line where it is a set."""
    return _inline(value) if isinstance(value, frozenset) else _literal(value, indent)


def _inline(value: object) -> str:
    """`value` as a Python expression on one line."""
    if isinstance(value, IntEnum):
        return f"{type(value).__name__}.{value.name}"
    if isinstance(value, bool | int | float):
        return repr(value)
    if isinstance(value, frozenset):
        return (
            f"frozenset({{{', '.join(_inline(member) for member in sorted(value, key=_order))}}})"
            if value
            else "frozenset()"
        )
    if isinstance(value, tuple):
        members = ", ".join(_inline(member) for member in value)
        return f"({members},)" if len(value) == 1 else f"({members})"
    if isinstance(value, Mapping):
        entries = sorted(value.items(), key=lambda entry: _order(entry[0]))
        return f"MappingProxyType({{{', '.join(f'{_inline(k)}: {_inline(v)}' for k, v in entries)}}})"
    if is_dataclass(value) and not isinstance(value, type):
        given = ", ".join(f"{name}={_inline(member)}" for name, member in _given_fields(value))
        return f"{type(value).__name__}({given})"
    raise TypeError(f"no literal for {value!r}")


def _given_fields(value: object) -> list[tuple[str, object]]:
    """The fields the dataclass `value` is constructed with, by name: those its constructor takes, but for those at
    their defaults."""
    taken = [(field.name, getattr(value, field.name)) for field in fields(value) if field.init]  # type: ignore[arg-type]
    return [(name, member) for name, member in taken if member != _default(value, name)]


def _default(value: object, name: str) -> object:
    """The default of the dataclass `value`'s field `name`, or `MISSING`, which no value equals."""
    field = next(field for field in fields(value) if field.name == name)  # type: ignore[arg-type]
    return field.default_factory() if field.default_factory is not MISSING else field.default


def _is_add_on(unit_type: UnitTypeId) -> bool:
    return "TECH_LAB" in unit_type.name or "REACTOR" in unit_type.name


def _order(value: object) -> str:
    return value.name if isinstance(value, IntEnum) else str(value)


def _trials(findings: Mapping[str, object]) -> list[Trial]:
    trials: list[Trial] = []
    for record in _records(findings["made"]):
        performer, ability = _unit_type(str(record["performer"])), _game_ability(str(record["ability"]))
        product = _unit_type(str(record["product"]))
        if performer is not None and ability is not None and product is not None:
            trials.append((performer, ability, product, str(record["result"])))
    return trials


def _unit_type(name: str) -> UnitTypeId | None:
    return UnitTypeId.get(RawUnitTypeId[name]) if name in RawUnitTypeId.__members__ else None


def _game_ability(name: str) -> RawAbilityId | None:
    """The game's own ability `name`, whether or not a curated id stands for it."""
    return RawAbilityId[name] if name in RawAbilityId.__members__ else None


def _fold(ability: RawAbilityId) -> AbilityId | None:
    """The curated id that stands for the game's `ability`: its own, or the id of an action several types perform."""
    return AbilityId.get(ability)


def _folded(ability: RawAbilityId) -> AbilityId:
    if (curated := _fold(ability)) is None:
        raise ValueError(f"no curated id stands for {ability.name}")
    return curated


def _ability(name: str) -> AbilityId | None:
    """The curated id that stands for the game's ability `name`."""
    return None if (ability := _game_ability(name)) is None else _fold(ability)


def _upgrade(name: str) -> UpgradeId | None:
    return UpgradeId.get(RawUpgradeId[name]) if name in RawUpgradeId.__members__ else None


def _required[IdT](lookup: Callable[[str], IdT | None], names: object) -> Iterable[IdT]:
    """Each name as its curated id, raising where one has none."""
    for name in _strings(names):
        if (member := lookup(name)) is None:
            raise ValueError(f"{name} is required, and no curated id names it")
        yield member


def _mapping(value: object) -> dict[str, object]:
    assert isinstance(value, dict)
    return {str(key): item for key, item in value.items()}


def _strings(value: object) -> list[str]:
    assert isinstance(value, list)
    return [str(item) for item in value]


def _records(value: object) -> list[dict[str, object]]:
    assert isinstance(value, list)
    return [_mapping(item) for item in value]


