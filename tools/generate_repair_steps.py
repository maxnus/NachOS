"""Generate `sc2nachos/gamedata/_repair_steps.py` from `data/repair.json`, written by `tools/sweep_repair.py`.

Refuses the findings if a type could not be made, its repair could not be measured, its health fell while it was
watched, or what it cost was not a quarter of what the tables say the type costs, for the share of its health repaired,
each resource rounded up. Writes that quarter, which `Unit.required_repair_cost` and `Unit.total_repair_cost` answer
from, and, under its curated id, the steps one SCV takes to repair a type from no health to whole, to the nearest step,
for each type whose repair is more than `MEASUREMENT_ERROR_STEPS` off the build steps of each of its stages that cost
something, which `Unit` answers for the rest. Runs without StarCraft II::

    uv run python tools/generate_repair_steps.py
"""

import json
import math
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from sc2nachos.ids import UnitTypeId

REPO = Path(__file__).parents[1]
INPUT = REPO / "data" / "repair.json"
OUTPUT = REPO / "src" / "sc2nachos" / "gamedata" / "_repair_steps.py"
# The fraction of what a type costs that repairing all its health costs.
REPAIR_COST_FRACTION = 0.25
# A repair measured within this many steps of its type's costing stages takes those steps: the 44 types that do were
# measured 4 below to 10 above them, and the six that do not 160 to 798 off (build 75689).
MEASUREMENT_ERROR_STEPS = 16

HEADER = '''"""What a repair by one SCV costs, and the steps it takes from no health to whole for each Terran mechanical
type that does not take the build steps of each of its stages that cost something, as `tools/sweep_repair.py` measured
them on build {base_build}.

DO NOT EDIT. Generated by `tools/generate_repair_steps.py` from `data/repair.json`.
"""

from types import MappingProxyType
from typing import Final

from sc2nachos.ids import UnitTypeId
'''


def read(findings: Mapping[str, Any]) -> dict[UnitTypeId, int]:
    """The steps a repair of its whole health takes, by its curated id, for each type `findings` measured more than
    `MEASUREMENT_ERROR_STEPS` off the build steps of each of its stages that cost something."""
    repair_steps = {}
    for name, repair in findings["repairs"].items():
        if "error" in repair:
            raise ValueError(f"the sweep could not repair a {name}: {repair['error']}")
        if repair["steps_for_whole_health"] is None:
            raise ValueError(f"no repair of a {name} was measured: {repair['order_result']}")
        if "cost_steps" not in repair:
            raise ValueError(f"the findings for a {name} predate `cost_steps`: sweep again")
        if repair["health_fell_step"] is not None:
            raise ValueError(f"the health of the {name} repaired fell at step {repair['health_fell_step']}")
        repaired, health_max = repair["health_repaired"], repair["health_max"]
        spent = (repair["minerals_spent"], repair["vespene_spent"])
        expected = tuple(repair_cost(repaired, health_max, repair[cost]) for cost in ("minerals_cost", "vespene_cost"))
        if spent != expected:
            raise ValueError(
                f"repairing {repaired} of a {name}'s {health_max} health cost {spent}, not a quarter of its cost,"
                f" {expected}"
            )
        if abs(repair["steps_for_whole_health"] - repair["cost_steps"]) > MEASUREMENT_ERROR_STEPS:
            repair_steps[UnitTypeId[name]] = round(repair["steps_for_whole_health"])
    return repair_steps


def repair_cost(repaired: float, health_max: float, cost: float) -> int:
    """What repairing `repaired` of a unit's `health_max` costs of one resource, of which its type costs `cost`,
    worked out as `Unit.required_repair_cost` does."""
    return math.ceil(repaired * cost * REPAIR_COST_FRACTION / health_max)


def render(repair_steps: Mapping[UnitTypeId, int], base_build: int) -> str:
    """The module source for `repair_steps`, one entry a type, sorted by name."""
    entries = "".join(
        f"        UnitTypeId.{unit_type.name}: {repair_steps[unit_type]},\n"
        for unit_type in sorted(repair_steps, key=lambda unit_type: unit_type.name)
    )
    return (
        HEADER.format(base_build=base_build)
        + "\n# A whole repair costs this fraction of what the type costs, each resource rounded up.\n"
        + f"REPAIR_COST_FRACTION: Final = {REPAIR_COST_FRACTION}\n"
        + "\n# The steps a whole repair takes of each type for which it is not the build steps of each of its stages\n"
        + "# that cost something.\n"
        + f"REPAIR_STEPS_EXCEPTIONS: Final = MappingProxyType(\n    {{\n{entries}    }}\n)\n"
    )


if __name__ == "__main__":
    findings = json.loads(INPUT.read_text(encoding="utf-8"))
    repair_steps = read(findings)
    OUTPUT.write_text(render(repair_steps, findings["base_build"]), encoding="utf-8")
    print(f"{OUTPUT.name}: {len(repair_steps)} unit types not repaired in their cost's steps")
