"""Generate `sc2nachos/gamedata/_footprints.py` from `data/footprints.json`, written by `tools/sweep_placement.py`.

Keeps the types that stand, under their curated ids, and refuses a footprint whose measured position and tiles
disagree with how a footprint centers. Runs without StarCraft II::

    uv run python tools/generate_footprints.py
"""

import json
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from sc2nachos.geometry import Footprint, Point, Tile
from sc2nachos.ids import UnitTypeId
from sc2nachos.ids.raw import RawUnitTypeId

REPO = Path(__file__).parents[1]
INPUT = REPO / "data" / "footprints.json"
OUTPUT = REPO / "src" / "sc2nachos" / "gamedata" / "_footprints.py"
_LINE_LENGTH = 120

HEADER = '''"""The tiles each structure and each of the map's units covers where it stands, as
`tools/sweep_placement.py` measured them on build {base_build}.

DO NOT EDIT. Generated by `tools/generate_footprints.py` from `data/footprints.json`.
"""

from types import MappingProxyType
from typing import Final

from sc2nachos.geometry import Footprint
from sc2nachos.ids import UnitTypeId

FOOTPRINTS: Final = MappingProxyType(
    {{
'''

FOOTER = """    }
)
"""


def read(findings: Mapping[str, Any]) -> dict[UnitTypeId, Footprint]:
    """The footprint of each type `findings` measured standing, by its curated id."""
    footprints = {}
    for name, measured in findings["unit_types"].items():
        unit_type = UnitTypeId.read(RawUnitTypeId[name])
        footprint = Footprint.from_rows(*measured["rows"])
        if measured["touches_edge"]:
            raise ValueError(f"{name} may reach past the tiles the sweep asked about")
        if measured["rows"]:
            centered = footprint.lower_left_tile(Point(tuple(measured["position"])))
            if centered != Tile(*measured["lower_left"]):
                raise ValueError(
                    f"{name} at {measured['position']} covered tiles from {measured['lower_left']}, but its footprint"
                    f" centers on tiles from {tuple(centered)}"
                )
        footprints[unit_type] = footprint
    return footprints


def render(footprints: Mapping[UnitTypeId, Footprint], base_build: int) -> str:
    """The module source for `footprints`, one entry a type, sorted by name."""
    entries = []
    for unit_type in sorted(footprints, key=lambda unit_type: unit_type.name):
        footprint = footprints[unit_type]
        key = f"        UnitTypeId.{unit_type.name}: "
        rows = _rows(footprint)
        if footprint.mask.all() and footprint.width == footprint.height and footprint.width:
            entries.append(f"{key}Footprint.square({footprint.width}),\n")
        elif len(one_line := f"{key}Footprint.from_rows({', '.join(rows)}),") <= _LINE_LENGTH:
            entries.append(one_line + "\n")
        else:
            lines = "".join(f"            {row},\n" for row in rows)
            entries.append(f"{key}Footprint.from_rows(\n{lines}        ),\n")
    return HEADER.format(base_build=base_build) + "".join(entries) + FOOTER


def _rows(footprint: Footprint) -> list[str]:
    """The rows that draw `footprint`, the top row first, each quoted."""
    return [
        '"' + "".join("#" if footprint.mask[x, y] else "." for x in range(footprint.width)) + '"'
        for y in reversed(range(footprint.height))
    ]


if __name__ == "__main__":
    findings = json.loads(INPUT.read_text(encoding="utf-8"))
    footprints = read(findings)
    OUTPUT.write_text(render(footprints, findings["base_build"]), encoding="utf-8")
    shapes = len(set(footprints.values()))
    print(f"{OUTPUT.name}: {len(footprints)} unit types, {shapes} footprints; not made: {findings['not_made']}")
